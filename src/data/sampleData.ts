import type { MediaItem } from '../types/media'

/**
 * Local sample catalogue, used when no TMDB credentials are configured.
 *
 * All titles and descriptions are fictional. Images are served by Lorem Picsum
 * (https://picsum.photos), which hosts photos published under the Unsplash
 * licence. Seeded URLs always return the same photo, so the layout is stable.
 */
const image = (seed: string, width: number, height: number) =>
  `https://picsum.photos/seed/nightflix-${seed}/${width}/${height}`

type SampleInput = Omit<MediaItem, 'year' | 'poster' | 'backdrop'> & {
  /** Set to false for titles that have no artwork yet. */
  hasArtwork?: boolean
}

const toMediaItem = ({ hasArtwork = true, ...item }: SampleInput): MediaItem => ({
  ...item,
  year: item.releaseDate ? Number(item.releaseDate.slice(0, 4)) : null,
  poster: hasArtwork ? image(item.id, 400, 600) : null,
  backdrop: hasArtwork ? image(`${item.id}-wide`, 1600, 900) : null,
})

